import pandas as pd
import numpy as np
from scipy.stats import zscore
data = {
    "Student": ["A", "B", "C", "D", "E", "F", "G", "H", "I", "J"],
    "Marks": [50, 55, 60, 62, 65, 68, 70, 72, 75, 150]
}
df = pd.DataFrame(data)
print(df)

Q1 = df["Marks"].quantile(0.25)
print(Q1)
Q3 = df["Marks"].quantile(0.75)
print(Q3)

IQR = Q3 - Q1
print(IQR)

lower = Q1 - 1.5 * IQR
print(lower)
upper = Q3 + 1.5 * IQR
print(upper)

outliers = df[(df["Marks"] < lower) | (df["Marks"] > upper)]
print(outliers)

df["Marks_Treated"] = np.where(df["Marks"] < lower, lower, df["Marks"])
df["Marks_Treated"] = np.where(df["Marks_Treated"] > upper, upper, df["Marks_Treated"])

print(df)

df_capped = df.copy()
df["Marks_Treated"] = df["Marks"].clip(lower, upper)

print("\nAfter Capping:")
print(df)

